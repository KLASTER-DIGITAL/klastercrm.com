/** Разряды неразрывным пробелом. Своя функция вместо toLocaleString: результат
 *  обязан совпасть на сервере и в браузере, а ICU у них разный. */
function ru(n: number): string {
  return String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
}

