import type { Metadata } from 'next';
import Link from 'next/link';
import { SiteShell } from '@/app/site/shell';

/**
 * 404. Задача страницы одна: не оставить посетителя в тупике.
 *
 * Три выхода вместо одного «на главную» — потому что сюда приходят из разных
 * мест: из письма (ссылка устарела), из поиска (адрес поменялся вместе с
 * переездом продукта под /widgets/analytics/) и из виджета. Главная никому из
 * троих не отвечает на вопрос, с которым он шёл.
 *
 * Тон ровный, без шуток и без «ой». Шутка на странице ошибки сообщает, что
 * ошибку никто не считает своей проблемой, а мы весь сайт строим на обратном.
 */

export const metadata: Metadata = {
  /* Точный заголовок из спецификации (раздел 2, строка /404). `absolute`, а не
     строка: шаблон layout дописал бы «— KLASTER» второй раз. */
  title: { absolute: 'Страницы нет — KLASTER' },
  description:
    'По этому адресу ничего нет. Три выхода: демо виджета аналитики, документация и поддержка.',
  /* Битые адреса в индексе не нужны. Next.js ставит на 404 свой noindex сам,
     так что в разметке тег появится дважды — оба запрещают индексацию, и это
     дешевле, чем полагаться на поведение фреймворка молча. */
  robots: { index: false, follow: true },
};

/** Три выхода. Порядок — по частоте, с которой они закрывают вопрос. */
const EXITS: { title: string; text: string; href: string; action: string }[] = [
  {
    title: 'Демо',
    text: 'Вкладки виджета на обезличенных данных пилотного аккаунта. Без регистрации и без доступа к вашей CRM.',
    href: '/widgets/analytics/demo',
    action: 'Открыть демо',
  },
  {
    title: 'Документация',
    text: 'Быстрый старт, разметка этапов, метрики и формулы, качество данных. Если вы искали конкретный раздел справки — он здесь.',
    href: '/widgets/analytics/docs',
    action: 'К документации',
  },
  {
    title: 'Поддержка',
    text: 'Telegram, WhatsApp и почта. Промежуточной линии нет: обращение читает инженер.',
    href: '/support',
    action: 'Написать',
  },
];

export default function NotFound() {
  return (
    <SiteShell>
      <h1 className="site-h1">Страницы нет</h1>
      <p className="site-lead">
        По этому адресу ничего не открывается. Сайт молодой: разделы появляются и переезжают, так
        что ссылка из закладок, письма или чужого поста могла устареть.
      </p>

      <div className="site-grid site-grid--3">
        {EXITS.map((e) => (
          <div className="site-card" key={e.href}>
            <h2 className="site-h3">{e.title}</h2>
            <p className="site-p">{e.text}</p>
            <p style={{ marginTop: 14 }}>
              <Link className="btn btn--sm" href={e.href}>
                {e.action}
              </Link>
            </p>
          </div>
        ))}
      </div>

      <h2 className="site-h2">Если этот адрес дали вам мы</h2>
      <p className="site-p">
        В письме, в счёте или внутри виджета — сообщите в поддержку, какой адрес не открылся.
        Поправим ссылку у себя, а не будем ждать, пока на неё наткнётся следующий. Заодно можно
        начать с <Link href="/widgets/analytics">страницы продукта</Link> — там весь состав виджета
        и цена одной страницей.
      </p>
    </SiteShell>
  );
}
