-- ── Письма о сроке лицензии: что уже отправлено ───────────────────────────
--
-- ЗАЧЕМ. 04.11.2026 у Like House встало распределение: лицензия кончилась
-- 31.10, трое суток льготного периода прошли незаметно, и в ночь на 04.11
-- заявки перестали расходиться по менеджерам. Никто не узнал заранее, потому
-- что предупреждать было нечем: виджет умеет посчитать «осталось три дня», но
-- канала доставки у него нет вовсе. Теперь за сроком следит кабинет — он один
-- знает и дату, и продукт, и кому писать (K-378).
--
-- Эта таблица отвечает на один вопрос: об этом событии уже писали? Без неё
-- суточный проход слал бы одно и то же письмо каждый день до самого конца
-- срока, и его перестали бы открывать — ровно к тому дню, когда оно важно.
--
-- PERIOD_END В ПЕРВИЧНОМ КЛЮЧЕ — не для порядка, а чтобы продление сбрасывало
-- отметки. Серия писем привязана к КОНКРЕТНОМУ сроку: продлили лицензию до
-- новой даты — это новая серия, и предупреждения придут снова. Без этого поля
-- продлённая лицензия второй раз истекла бы молча: отметки «уже писали» лежат,
-- а дата другая.
--
-- ХРАНИМ И ТО, ЧТО НЕ ОТПРАВИЛИ. `outcome` отличает ушедшее письмо от
-- пропущенного (суточный проход не сработал, и напоминание «за семь дней» уже
-- бессмысленно за два), от письма без адресата и от сбоя почты. Отметка с
-- любым исходом закрывает событие: повторять нечего, а причина молчания
-- остаётся видимой. Иначе единственный способ узнать, почему письма не было, —
-- догадка.
--
-- Миграция идемпотентна: повторный прогон ничего не меняет.

create table if not exists license_notices (
  account_id  bigint not null,
  product     text not null,
  -- d7 | d3 | d1 — за столько суток до конца; expired — срок кончился, пошёл
  -- льготный период; stopped — льготный период кончился, виджет остановлен;
  -- no_license — виджет спрашивал лицензию, которой в кабинете нет.
  kind        text not null,
  -- Срок, к которому относится серия. Для no_license срока нет — там epoch,
  -- а событие закрывается на сутки колонкой `at` (письмо не чаще раза в день).
  period_end  timestamptz not null,
  at          timestamptz not null default now(),
  outcome     text not null,
  -- Кому ушло: адреса в открытом виде, их видит только владелец линейки.
  -- Нужны, чтобы по журналу можно было ответить «почему клиент не получил».
  recipients  text[] not null default '{}',
  error       text,
  primary key (account_id, product, kind, period_end),
  constraint license_notices_kind_chk
    check (kind in ('d7', 'd3', 'd1', 'expired', 'stopped', 'no_license')),
  constraint license_notices_outcome_chk
    check (outcome in ('sent', 'skipped_late', 'no_recipient', 'failed'))
);

create index if not exists license_notices_at_idx on license_notices (at desc);

comment on table license_notices is
  'Письма о сроке лицензии: одно на событие. Ключ включает period_end, поэтому продление начинает новую серию предупреждений.';
comment on column license_notices.outcome is
  'sent — письмо ушло; skipped_late — событие уже не актуально (проход пропустил день), письма не было намеренно; no_recipient — писать некому; failed — почта не приняла.';
