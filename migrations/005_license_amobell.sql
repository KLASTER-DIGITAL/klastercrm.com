-- ── Третий продукт линейки: KLASTER AMOBELL ────────────────────────────────
--
-- ЗАЧЕМ. Колокол (поздравления с выигранной сделкой) спрашивает лицензию у
-- того же кабинета с `product: 'klaster_amobell'`. Роут уже знает продукт, но
-- без этой миграции строку лицензии колокола база не примет: словарь
-- `licenses_web_product_chk` из 003 знает только два продукта. Лицензия, которую
-- нельзя завести, — это клиент, который заплатил и остался на триале.
--
-- СОВМЕСТИМОСТЬ. Словарь только расширяется: все строки аналитики и
-- распределения ему удовлетворяют, роут для них отвечает как вчера. Тарифы не
-- трогаем: у колокола возможности от плана не зависят, `plan` у его строк — null,
-- а null словарь планов из 003 допускает.
--
-- Миграция идемпотентна: повторный прогон ничего не меняет. 003 при повторном
-- прогоне это ограничение не трогает (см. её комментарий), поэтому `migrate`
-- проходит и на базе, где лицензии колокола уже есть.

alter table licenses_web drop constraint if exists licenses_web_product_chk;
alter table licenses_web add constraint licenses_web_product_chk
  check (product in ('klaster_analytics', 'klaster_distribution', 'klaster_amobell'));

comment on column licenses_web.product is
  'Продукт линейки: klaster_analytics | klaster_distribution | klaster_amobell. Ключ лицензии привязан к паре (аккаунт, продукт): подписка на один продукт не открывает другой.';
