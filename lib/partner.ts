export interface PartnerTier {
  /** Внутренний код. В базу не пишется — считается из числа клиентов. */
  code: 'base' | 'pro' | 'expert';
  /** Сколько активных клиентов нужно, чтобы попасть на ступень. */
  from: number;
  /** Процент с каждого платежа клиента за подписку. */
  rate: number;
  name: { ru: string; en: string };
}

export const PARTNER_TIERS: readonly PartnerTier[] = [
  { code: 'base', from: 1, rate: 30, name: { ru: 'Партнёр', en: 'Partner' } },
  { code: 'pro', from: 5, rate: 40, name: { ru: 'Партнёр Про', en: 'Partner Pro' } },
  { code: 'expert', from: 10, rate: 50, name: { ru: 'Партнёр Эксперт', en: 'Partner Expert' } },
];

/**
 * Процент с услуг, которые по приведённому клиенту выполняем мы сами: партнёр
 * передал контакт, дальше всё делаем мы. Та же ставка, что у F5, ГЕНЕЗИСа и
 * Integrator2, — рынок сошёлся на десяти процентах за передачу контакта.
 */
export const SERVICE_RATE = 10;

/** Сколько ждём до подтверждения начисления — срок возврата платежа. */
export const HOLD_DAYS = 14;

/**
 * Минимальная сумма выплаты. Рынок держит порог около 5 000 ₽ (Bitrix24,
 * экосистема amoCRM); пятьдесят долларов — тот же порядок в нашей валюте.
 */
export const MIN_PAYOUT_USD = 50;

/** Клиент закреплён за партнёром навсегда с первого касания. */
export const FIXED_FOREVER = true;

/** Сколько живёт метка в браузере до первой заявки. */
export const COOKIE_DAYS = 90;

/** Ставка по числу активных клиентов. Ноль клиентов — ставка входа. */
export function partnerTier(activeClients: number): PartnerTier {
  let tier = PARTNER_TIERS[0]!;
  for (const t of PARTNER_TIERS) if (activeClients >= t.from) tier = t;
  return tier;
}

export function partnerRate(activeClients: number): number {
  return partnerTier(activeClients).rate;
}

/**
 * Начисление с одного платежа. Считается в центах и округляется вниз:
 * округление вверх в нашу сторону — мелочь, из-за которой партнёр перестаёт
 * верить всей таблице.
 */
export function commissionCents(
  baseCents: number,
  kind: 'subscription' | 'service',
  activeClients: number,
): { rate: number; amountCents: number } {
  const rate = kind === 'service' ? SERVICE_RATE : partnerRate(activeClients);
  return { rate, amountCents: Math.floor((baseCents * rate) / 100) };
}

/**
 * Сколько партнёр заработает за год с одного клиента на указанном тарифе.
 * Нужно витрине: «сколько я получу» — первый вопрос партнёра, и отвечать на
 * него надо числом, а не процентом.
 */
export function yearlyEarningsUsd(monthlyPriceUsd: number, activeClients: number): number {
  return Math.round((monthlyPriceUsd * 12 * partnerRate(activeClients)) / 100);
}

/** Реферальная ссылка партнёра. Метка одна и та же в ссылке и в промокоде. */
export const REF_PARAM = 'p';

export function referralLink(origin: string, code: string): string {
  return `${origin}/?${REF_PARAM}=${code}`;
}
