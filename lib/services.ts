/** Список CRM словами: «amoCRM и Bitrix24». */
export function crmList(crm: readonly Crm[]): string {
  const names = crm.map((c) => CRM_NAME[c]);
  if (names.length <= 1) return names[0] ?? '';
  return `${names.slice(0, -1).join(', ')} и ${names[names.length - 1]}`;
}
