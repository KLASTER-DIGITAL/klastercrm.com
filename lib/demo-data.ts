export type StageKind = 'sales' | 'parking' | 'unsorted' | 'won' | 'lost';

export interface Account {
  name: string;
  subdomain: string;
  accountId: number;
  currency: string;
  tz: string;
  usersTotal: number;
  amoTariff: string;
}

export interface Pipeline {
  id: number;
  name: string;
  transitions: number;
  newJul: number;
  isMain: boolean;
}

export interface Stage {
  pipelineId: number;
  statusId: number; // ключ этапа — пара (pipelineId, statusId), не имя
  name: string;
  sort: number;
  kind: StageKind;
  amoColor: string;
  enteredJul: number;
  enteredJun: number;
  medianDays: number | null;
  observations: number;
}

export interface Manager {
  /**
   * id пользователя amoCRM. В живом источнике — настоящий, в демо — условный:
   * демо-сессия сохранять отчёты не может, поэтому точность здесь не нужна,
   * но поле обязано быть — сохранённые отчёты ссылаются на менеджера по id,
   * а не по индексу массива, который пересобирается на каждый период.
   * 0 — автоматика (как в живых данных).
   */
  id: number;
  /** Подпись для интерфейса: имя из справочника, «Автоматика», «Удалённый пользователь (#id)». */
  name: string;
  jul: number;
  jun: number;
  isBot: boolean;
  /** false — пользователя нет в справочнике аккаунта (см. lib/manager-label.ts). */
  known?: boolean;
  /** Группа пользователя amoCRM. null — группы нет либо она не синхронизирована. */
  groupId: number | null;
}

/** Тип работы группы: от него зависит, какие метрики для неё осмысленны. */
export type GroupKind = 'sales' | 'partner' | 'service' | 'office' | 'unset';

export interface UserGroup {
  id: number;
  name: string;
  kind: GroupKind;
  /** false — тип угадан по названию и не подтверждён администратором. */
  isConfirmed: boolean;
  users: number;
}

/** Кортеж факта: [индекс этапа, индекс менеджера, индекс проекта, месяц (1 = июль, 0 = июнь), количество].
    Порядок полей — как деструктурирует app.js прототипа: [si, mi, pi, mo, n]. */
/** [этап, менеджер, проект, период, n, fresh?, first?] — fresh = 1: сделка
    создана в этом же периоде; first = 1: это первый вход сделки в этап внутри
    периода (даёт «уникальных сделок», складывающееся по любым срезам).
    У демо-выгрузки обоих признаков нет, поэтому они необязательны. */
export type FactRow = readonly [number, number, number, number, number, number?, number?];

export interface Flow { from: string; to: string; n: number }
export interface CrossFlow { fromPipe: string; toPipe: string; n: number }
