/**
 * СЕКРЕТЫ ИНТЕГРАЦИЙ amoCRM, которыми подписан X-Auth-Token.
 *
 * Зачем список, а не одна строка. Один и тот же наш сервер обслуживает
 * РАЗНЫЕ интеграции amoCRM одновременно:
 *
 *   - публичную интеграцию из технического аккаунта (маркетплейс),
 *   - приватные интеграции, заведённые в аккаунтах клиентов до модерации.
 *
 * У каждой интеграции свой секретный ключ, и `$authorizedAjax` подписывает
 * токен ключом ТОЙ интеграции, из которой открыт виджет. С единственным
 * `AMO_CLIENT_SECRET` подпись клиента с приватной интеграцией не сходится, и
 * виджет получает 401 — ровно та ошибка, которую мы ловили 26.08.2026 на
 * техаккаунте (docs/УСТАНОВКА-ВИДЖЕТА.md).
 *
 * Поэтому проверка идёт по списку: токен принимается, если он проходит хотя бы
 * по одному известному секрету. Перебор безопасен — это HMAC над уже
 * полученной строкой, а не подбор: неверная подпись не пройдёт ни по одному
 * ключу. Порядок задаёт только скорость, не результат.
 *
 * ENV:
 *   AMO_CLIENT_SECRET   — основной (публичная интеграция маркетплейса);
 *   AMO_CLIENT_SECRETS  — дополнительные, через запятую/перевод строки
 *                         (приватные интеграции клиентов на время пилота).
 */

/** Минимальная длина, ниже которой строка на секрет не похожа. */
const MIN_LEN = 16;

/** Разобрать значение переменной: одна строка либо список через запятую/перевод строки. */
function split(value: string | undefined): string[] {
  if (value === undefined) return [];
  return value
    .split(/[,\n]/)
    .map((s) => s.trim())
    .filter((s) => s.length >= MIN_LEN);
}

/**
 * Все известные секреты интеграций, без повторов и в порядке приоритета.
 * Пустой список означает, что проверять подпись нечем — вызывающий обязан
 * ответить отказом, а не пускать без проверки.
 */
export function amoClientSecrets(): string[] {
  const all = [...split(process.env['AMO_CLIENT_SECRET']), ...split(process.env['AMO_CLIENT_SECRETS'])];
  return [...new Set(all)];
}
